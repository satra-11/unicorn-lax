export function getSceneJapanese(label: string | undefined): string {
  if (!label) return '不明'
  
  // マッピングがあればそれを返す
  if (sceneTranslations[label]) {
    return sceneTranslations[label]
  }

  // なければスラッシュとアンダースコアを読みやすくしてフォールバック
  const parts = label.split('/')
  const name = parts[parts.length - 1]
  if (!name) return label
  return name.replace(/_/g, ' ')
}
